    function traditionalToSimplifiedText(text) {
      return text.split('').map(ch => traditionalToSimplified[ch] || ch).join('')
    }

    function fullWidthToHalfWidth(text) {
      let result = ''
      for (let i = 0; i < text.length; i++) {
        const code = text.charCodeAt(i)
        if (code >= 0xff01 && code <= 0xff5e) {
          result += String.fromCharCode(code - 0xfee0)
        } else if (code === 0x3000) {
          result += ' '
        } else {
          result += text[i]
        }
      }
      return result
    }

    function halfWidthToFullWidth(text) {
      let result = ''
      for (let i = 0; i < text.length; i++) {
        const code = text.charCodeAt(i)
        if (code >= 0x21 && code <= 0x7e) {
          result += String.fromCharCode(code + 0xfee0)
        } else if (code === 0x20) {
          result += '　'
        } else {
          result += text[i]
        }
      }
      return result
    }

    function capitalizeFirst(str) {
      if (!str) return str
      return str.charAt(0).toUpperCase() + str.slice(1)
    }

    function capitalizeEachWord(str) {
      return str.replace(/\b\w/g, ch => ch.toUpperCase())
    }

