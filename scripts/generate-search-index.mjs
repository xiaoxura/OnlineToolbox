// Generates src/tools/search-index.js: pinyin spellings for every tool name so
// the search box accepts "sjc" → 时间戳 or "zhengze" → 正则 without shipping a
// pinyin runtime to the browser.
//
// Run automatically before a production build; `--check` verifies the committed
// file is in sync with the registry (used by CI).
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pinyin } from 'pinyin-pro'
import { tools } from '../src/tools/registry.js'

const path = resolve('src/tools/search-index.js')

function pinyinFor(name) {
  const full = pinyin(name, { toneType: 'none', type: 'array', nonZh: 'consecutive' })
    .map(part => part.trim().toLowerCase())
    .filter(Boolean)
  const initials = pinyin(name, { pattern: 'first', toneType: 'none', type: 'array', nonZh: 'consecutive' })
    .map(part => part.trim().toLowerCase())
    .filter(Boolean)
  const fullWord = full.join('')
  const initialWord = initials.join('')
  return [...new Set([fullWord, full.join(' '), initialWord])]
    .filter(Boolean)
    .join(' ')
}

const entries = tools.map(tool => [tool.id, pinyinFor(tool.name)])
const body = entries
  .map(([id, value]) => `  ${JSON.stringify(id)}: ${JSON.stringify(value)}`)
  .join(',\n')
const source = `// Generated by scripts/generate-search-index.mjs — do not edit by hand.
// Pinyin spellings (full + spaced + initials) used by tool search.
export const searchPinyin = {
${body}
}
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = await readFile(path, 'utf8')
  } catch {
    current = ''
  }
  if (current !== source) {
    console.error('search-index.js is out of date. Run `npm run search:index` and commit the result.')
    process.exit(1)
  }
  console.log(`search-index.js is in sync with ${entries.length} tools.`)
} else {
  await writeFile(path, source)
  console.log(`Generated pinyin search index for ${entries.length} tools.`)
}
